// Regenerates THIRD_PARTY_NOTICES.md from the production npm dependency tree (what ends up in ui/dist).
//   cd ui && npm ci && cd .. && node scripts/gen_notices.js > THIRD_PARTY_NOTICES.md
const { execSync } = require('child_process');
const fs = require('fs'), path = require('path');
const ui = path.join(__dirname, '..', 'ui');
const tree = JSON.parse(execSync('npm ls --omit=dev --all --json', { cwd: ui, maxBuffer: 1 << 26 }).toString());
const seen = new Map();
(function walk(deps) {
  for (const [name, info] of Object.entries(deps || {})) {
    if (!seen.has(name)) seen.set(name, info.version);
    walk(info.dependencies);
  }
})(tree.dependencies);

const python = [
  ['libtorrent-rasterbar', 'BSD-3-Clause', 'https://github.com/arvidn/libtorrent', 'Installed from PyPI at setup time; not redistributed here.'],
  ['aiohttp', 'Apache-2.0', 'https://github.com/aio-libs/aiohttp', 'Installed from PyPI; not redistributed here.'],
  ['cryptography', 'Apache-2.0 OR BSD-3-Clause', 'https://github.com/pyca/cryptography', 'Installed from PyPI; not redistributed here.'],
];

let out = `# Third-party notices

Swarm itself is licensed per component (see the root README). It builds on the open-source software below.
The npm packages are bundled into the web UI and their notices are reproduced here as their licenses require.
This file is generated by \`scripts/gen_notices.js\`; do not edit by hand.

## Python dependencies (installed, not bundled)

| package | license | source | note |
|---|---|---|---|
${python.map((p) => `| ${p[0]} | ${p[1]} | ${p[2]} | ${p[3]} |`).join('\n')}

## npm packages bundled into the UI

`;
const names = [...seen.keys()].sort();
for (const name of names) {
  const dir = path.join(ui, 'node_modules', name);
  let pkg; try { pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')); } catch { continue; }
  const licFile = fs.readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\..*)?$/i.test(f));
  const text = licFile ? fs.readFileSync(path.join(dir, licFile), 'utf8').trim() : '(no license file shipped in the package; license declared in package.json)';
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url || '';
  out += `### ${name} ${pkg.version}\n\nLicense: ${pkg.license}${repo ? ` · ${repo.replace(/^git\+/, '').replace(/\.git$/, '')}` : ''}\n\n\`\`\`text\n${text}\n\`\`\`\n\n`;
}
process.stdout.write(out);
